export type ApiErrorCode = typeof API_ERROR_CODES[keyof typeof API_ERROR_CODES];

export function defaultApiErrorCode(status: number): ApiErrorCode {
  if (status === 401) return API_ERROR_CODES.AUTH_REQUIRED;
  if (status === 403) return API_ERROR_CODES.FORBIDDEN;
  if (status === 429) return API_ERROR_CODES.RATE_LIMITED;
  if (status === 502 || status === 503) return API_ERROR_CODES.SERVICE_UNAVAILABLE;
  if (status >= 400 && status < 500) return API_ERROR_CODES.VALIDATION_FAILED;
  return API_ERROR_CODES.INTERNAL_ERROR;
}
